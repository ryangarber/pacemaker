// Package state persists accepted baselines in plaintext, diff-friendly
// files:
//
//	.pacemaker/state.yaml                    one entry per (block, ref) link
//	.pacemaker/snapshots/<block>/<ref>.snap  upstream block content when accepted
//
// Snapshots make drift diffs self-contained: they work for non-git targets
// and survive upstream history rewrites.
package state

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/ryangarber/pacemaker/internal/config"
	"github.com/ryangarber/pacemaker/internal/ref"
)

// Baseline records the upstream state a local block was last aligned with.
type Baseline struct {
	Ref        string    `yaml:"ref"`
	Target     string    `yaml:"target"`
	Path       string    `yaml:"path"`
	Symbol     string    `yaml:"symbol,omitempty"`
	Range      ref.Range `yaml:"range,flow"`
	Revision   string    `yaml:"revision,omitempty"`
	FileHash   string    `yaml:"file_hash"`
	Hash       string    `yaml:"hash"`
	NormHash   string    `yaml:"norm_hash"`
	LocalHash  string    `yaml:"local_hash,omitempty"`
	AcceptedAt time.Time `yaml:"accepted_at"`
	AcceptedBy string    `yaml:"accepted_by,omitempty"`
}

// State is the full persisted state.
type State struct {
	Version int                    `yaml:"version"`
	Links   map[string][]*Baseline `yaml:"links"`

	root string
}

// Load reads state (an absent file yields an empty state).
func Load(root string) (*State, error) {
	s := &State{Version: 1, Links: map[string][]*Baseline{}, root: root}
	b, err := os.ReadFile(filepath.Join(root, config.Dir, config.StateFile))
	if os.IsNotExist(err) {
		return s, nil
	}
	if err != nil {
		return nil, err
	}
	if err := yaml.Unmarshal(b, s); err != nil {
		return nil, err
	}
	if s.Links == nil {
		s.Links = map[string][]*Baseline{}
	}
	return s, nil
}

// Save writes state.yaml deterministically.
func (s *State) Save() error {
	for _, bs := range s.Links {
		sort.Slice(bs, func(i, j int) bool { return bs[i].Ref < bs[j].Ref })
	}
	var buf bytes.Buffer
	buf.WriteString("# pacemaker state — generated by `pacemaker accept`. Commit this file.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(s); err != nil {
		return err
	}
	dir := filepath.Join(s.root, config.Dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, config.StateFile), buf.Bytes(), 0o644)
}

// Get returns the baseline for a block/ref pair.
func (s *State) Get(block, refKey string) *Baseline {
	for _, b := range s.Links[block] {
		if b.Ref == refKey {
			return b
		}
	}
	return nil
}

// Put inserts or replaces a baseline and writes its snapshot.
func (s *State) Put(block string, b *Baseline, snapshot []byte) error {
	list := s.Links[block]
	replaced := false
	for i, old := range list {
		if old.Ref == b.Ref {
			list[i] = b
			replaced = true
		}
	}
	if !replaced {
		list = append(list, b)
	}
	s.Links[block] = list
	p := s.SnapshotPath(block, b.Ref)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	return os.WriteFile(p, snapshot, 0o644)
}

// Remove deletes a block (all refs) or a single ref of a block.
func (s *State) Remove(block, refKey string) {
	if refKey == "" {
		for _, b := range s.Links[block] {
			_ = os.Remove(s.SnapshotPath(block, b.Ref))
		}
		delete(s.Links, block)
		_ = os.Remove(filepath.Join(s.root, config.Dir, config.SnapDir, safe(block)))
		return
	}
	var keep []*Baseline
	for _, b := range s.Links[block] {
		if b.Ref == refKey {
			_ = os.Remove(s.SnapshotPath(block, b.Ref))
			continue
		}
		keep = append(keep, b)
	}
	if len(keep) == 0 {
		delete(s.Links, block)
	} else {
		s.Links[block] = keep
	}
}

// Snapshot reads the stored upstream content for a baseline.
func (s *State) Snapshot(block, refKey string) ([]byte, error) {
	return os.ReadFile(s.SnapshotPath(block, refKey))
}

// SnapshotPath is where a baseline's snapshot lives.
func (s *State) SnapshotPath(block, refKey string) string {
	return filepath.Join(s.root, config.Dir, config.SnapDir, safe(block), safe(refKey)+".snap")
}

// Blocks returns sorted block IDs.
func (s *State) Blocks() []string {
	var ids []string
	for id := range s.Links {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	return ids
}

var unsafe = regexp.MustCompile(`[^A-Za-z0-9_.-]+`)

func safe(s string) string {
	out := strings.Trim(unsafe.ReplaceAllString(s, "_"), "_.")
	if len(out) > 120 {
		h := sha256.Sum256([]byte(s))
		out = out[:100] + "-" + hex.EncodeToString(h[:6])
	}
	if out == "" {
		out = "_"
	}
	return out
}

// Hash returns a short content hash.
func Hash(b []byte) string {
	h := sha256.Sum256(b)
	return hex.EncodeToString(h[:12])
}
